// Builds extension/changelog.json, the data the Changelog tab shows, from the
// release notes in docs/release-notes/<version>.md. The notes are the one
// place to write; the JSON is generated and is never edited by hand.
//
// A notes file is a date line, a blank line, then one bullet per line:
//
//   date: 2026-11-18
//
//   - Added something you can see.
//   - Fixed something that was wrong.
//
// Run from the repo root or anywhere:
//   node extension/scripts/changelog.mjs            writes extension/changelog.json
//   node extension/scripts/changelog.mjs --check    exits 1 when the file is out of date

import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { compareVersions, parseVersion } from '../shared/version.js';

const here = path.dirname(fileURLToPath(import.meta.url));
export const NOTES_DIR = path.resolve(here, '..', '..', 'docs', 'release-notes');
export const OUTPUT = path.resolve(here, '..', 'changelog.json');
export const NOTE =
  'Generated by extension/scripts/changelog.mjs from docs/release-notes. Do not edit; change the notes and run the script.';

export class NotesError extends Error {}

// One notes file's text as { date, items }, or a NotesError saying what is wrong.
export function parseNotes(text, name = 'notes') {
  const lines = text.replace(/\r\n?/g, '\n').split('\n');
  const first = /^date: (\d{4}-\d{2}-\d{2})$/.exec(lines[0] || '');
  if (!first) throw new NotesError(`${name}: the first line must be "date: YYYY-MM-DD"`);
  if (Number.isNaN(Date.parse(first[1]))) throw new NotesError(`${name}: "${first[1]}" is not a date`);
  if ((lines[1] || '') !== '') throw new NotesError(`${name}: leave a blank line after the date`);
  const items = [];
  for (const [i, line] of lines.slice(2).entries()) {
    if (line === '') continue;
    const bullet = /^- (\S.*)$/.exec(line);
    if (!bullet) throw new NotesError(`${name}: line ${i + 3} must be a bullet starting with "- "`);
    if (/[–—]/.test(line)) throw new NotesError(`${name}: line ${i + 3} has a dash; use a comma, a period or a bracket`);
    items.push(bullet[1].trim());
  }
  if (!items.length) throw new NotesError(`${name}: write at least one bullet`);
  return { date: first[1], items };
}

// The releases in `dir`, newest first.
export function buildChangelog(dir = NOTES_DIR) {
  const releases = [];
  for (const file of fs.readdirSync(dir).sort()) {
    if (!file.endsWith('.md')) continue;
    const version = file.slice(0, -3);
    if (!parseVersion(version)) throw new NotesError(`${file}: the name must be a version like 1.4.0.md`);
    releases.push({ version, ...parseNotes(fs.readFileSync(path.join(dir, file), 'utf8'), file) });
  }
  releases.sort((a, b) => compareVersions(b.version, a.version));
  return { _: NOTE, releases };
}

export function serialize(changelog) {
  return `${JSON.stringify(changelog, null, 2)}\n`;
}

if (process.argv[1] && fs.realpathSync(process.argv[1]) === fileURLToPath(import.meta.url)) {
  try {
    const next = serialize(buildChangelog());
    if (process.argv.includes('--check')) {
      const current = fs.existsSync(OUTPUT) ? fs.readFileSync(OUTPUT, 'utf8') : '';
      if (current !== next) {
        console.error('extension/changelog.json is out of date. Run: node extension/scripts/changelog.mjs');
        process.exit(1);
      }
      console.log('extension/changelog.json is up to date.');
    } else {
      fs.writeFileSync(OUTPUT, next);
      console.log(`Wrote ${path.relative(process.cwd(), OUTPUT)}.`);
    }
  } catch (err) {
    if (!(err instanceof NotesError)) throw err;
    console.error(err.message);
    process.exit(1);
  }
}
